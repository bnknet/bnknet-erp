-- 주문별 판매 시점 원가 고정 (2026-10-01)
-- 배경: 공헌이익이 항상 '현재 재고 원가'로 계산돼, 재고 원가(평균단가 등)를 바꾸면 과거 주문의 공헌이익·마진율까지 바뀌었음.
-- 조치: 주문에 저장 시점의 개당 원가(unit_cost)를 기록하고, 공헌이익은 그 값으로 계산.
--       이후 원가를 바꿔도 과거 주문은 그대로, 바꾼 뒤 저장되는 주문부터만 새 원가 적용.
--   · 대상: 일반(사방넷 변환)·직접등록(수기) 주문. 도매/로켓그로스/과거실적은 이미 manual_cost 로 고정.
--   · 세트상품은 구성품 원가 합. 원가를 알 수 없으면 null(→ 현재 재고 원가로 계산).
--   · 기존 주문은 이 SQL 실행 후 일괄 채움 스크립트로 '현재 원가'를 한 번 기록해 지금 숫자를 그대로 고정.
-- 재실행 안전.

alter table public.orders add column if not exists unit_cost numeric;

