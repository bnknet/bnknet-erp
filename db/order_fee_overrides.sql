-- 주문번호별 몰수수료율(%) 오버라이드
-- 요율표(mall_fees)에 없거나 건별로 수수료가 다른 경우(예: 공구마다 수수료 상이) 특정 주문에만 수수료율 지정.
-- 해당 주문은 매출현황·주문조회·영업이익 공헌이익 계산에서 수수료 = 매출 × fee_rate% 로 반영(원가·매출은 기존 그대로).
-- 재실행 안전.
create table if not exists public.order_fee_overrides (
  order_number text primary key,   -- = orders.order_number
  fee_rate     numeric not null,   -- 몰 수수료율(%) 예: 45
  note         text,
  updated_at   timestamptz not null default now()
);

grant select, insert, update, delete on public.order_fee_overrides to anon;

